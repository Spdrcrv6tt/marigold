"""Build the flash image for the Imhotep core from the integer golden model file.

    .venv/Scripts/python.exe rtl/core/tools/mkimage.py data  --tag w8      -> data/core/<tag>/data.bin, layout.h
    .venv/Scripts/python.exe rtl/core/tools/mkimage.py flash --tag w8 --fw data/core/<tag>/fw.bin
                                                                           -> data/core/<tag>/flash.bin

Flash layout
    0x00000  "IMH1"
    0x00004  firmware length in bytes (u32 LE)
    0x00008  firmware (copied to PMEM by the boot sequencer)
    DATA_BASE (0x10000)  data.bin:
        one stream per weight site, row after row:
            bias  int40 LE   (accumulator units; 0 when the layer has none)
            M     u16 LE     requantise multiplier
            sh    u8         requantise right shift
            weights: fan_in int8, or fan_in int4 packed two per byte (low nibble first), row padded to a byte
        the embedding table as one more site (bias 0, proj.M, proj.sh): it is both the lookup table and the
        vocabulary projection
        EMBM   per token: emb.M u16, emb.sh u8, pad u8
        norms  per norm site, 288 records of 6 bytes: G int16, B int32 (channel order)
        ROPE   per position: cos int16[16], sin int16[16]
        VOCAB  u32[32769] offsets (relative to the piece area) then the piece bytes; pieces are already
               output text (U+2581 -> space, byte-fallback tokens -> the byte, special tokens -> empty)
layout.h carries the offsets, shapes, formats and the ROM tables for the firmware.
"""
import argparse, json, re, sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import golden

ROOT = Path(__file__).resolve().parents[3]
DATA_BASE = 0x10000
NL = 6


def mac_sites():
    s = [("conv1", "AUDIO", "conv1.out"), ("conv2", "gn.out", "conv2.out"), ("conv3", "conv2.out", "conv3.out")]
    for i in range(NL):
        n = f"enc{i}"
        s += [(n + ".q", n + ".ln1", n + ".q"), (n + ".k", n + ".ln1", n + ".k"), (n + ".v", n + ".ln1", n + ".v"),
              (n + ".o", n + ".v", "enc.res"), (n + ".fc1", n + ".ln2", n + ".fc1"), (n + ".fc2", n + ".fc1", "enc.res")]
    for i in range(NL):
        n = f"dec{i}"
        s += [(n + ".q", n + ".ln1", n + ".q"), (n + ".k", n + ".ln1", n + ".k"), (n + ".v", n + ".ln1", n + ".v"),
              (n + ".o", n + ".v", "dec.res"), (n + ".cq", n + ".ln2", n + ".cq"), (n + ".ck", "enc.ln", n + ".ck"),
              (n + ".cv", "enc.ln", n + ".cv"), (n + ".co", n + ".cv", "dec.res"),
              (n + ".fc1", n + ".ln3", n + ".fc1"), (n + ".fc2", n + ".prod", "dec.res")]
    return s


def norm_sites():
    s = ["gn.out", "enc.ln", "dec.ln"]
    for i in range(NL): s += [f"enc{i}.ln1", f"enc{i}.ln2", f"dec{i}.ln1", f"dec{i}.ln2", f"dec{i}.ln3"]
    return s


def pack_site(q, M, sh, bi, wbits):
    """-> bytes of one site stream."""
    out, fan = q.shape
    assert M.min() >= 0 and M.max() < 65536 and sh.min() >= 1 and sh.max() < 62
    assert np.abs(bi).max() < 2 ** 39
    hdr = np.zeros((out, 8), dtype=np.uint8)
    b = bi.astype(np.int64) & ((1 << 40) - 1)
    for j in range(5): hdr[:, j] = (b >> (8 * j)) & 255
    hdr[:, 5] = M & 255; hdr[:, 6] = M >> 8; hdr[:, 7] = sh
    if wbits == 8:
        body = q.astype(np.int8).view(np.uint8)
    else:
        assert wbits == 4 and q.min() >= -8 and q.max() <= 7
        n = q.astype(np.int64) & 15
        if fan % 2: n = np.concatenate([n, np.zeros((out, 1), dtype=np.int64)], axis=1)
        body = (n[:, 0::2] | (n[:, 1::2] << 4)).astype(np.uint8)
    return np.concatenate([hdr, body], axis=1).tobytes()


def vocab_pieces(model_id="UsefulSensors/moonshine-tiny"):
    from transformers import AutoProcessor
    tok = AutoProcessor.from_pretrained(model_id).tokenizer
    special = set(tok.all_special_ids)
    toks = tok.convert_ids_to_tokens(list(range(len(tok))))
    out = []
    for i, t in enumerate(toks):
        m = re.fullmatch(r"<0x([0-9A-Fa-f]{2})>", t)
        if i in special: out.append(b"")
        elif m: out.append(bytes([int(m.group(1), 16)]))
        else: out.append(t.replace("▁", " ").encode("utf-8"))
    return out, tok


def c_array(name, a, ctype):
    v = ", ".join(str(int(x)) for x in np.asarray(a).ravel())
    return f"static const {ctype} {name}[{np.asarray(a).size}] = {{{v}}};\n"


def rom_svh(G):
    """The ROMs of the per-element unit (rtl/core/imh_rom.svh): tanh / GELU / SiLU interpolation tables and exp2."""
    h = "// generated by rtl/core/tools/mkimage.py rom from the golden model ROM tables (lut.tanh/.gelu/.silu, sm.exp2);\n"
    h += "// do not edit. mkimage.py data checks every export against this file.\n"
    h += "function automatic signed [19:0] lut_rom(input [1:0] sel, input [9:0] idx);\n    case ({sel, idx})\n"
    for k, t in enumerate(("tanh", "gelu", "silu")):
        for j, v in enumerate(G["lut." + t]):
            v = int(v); h += "        12'd%d: lut_rom = %s20'sd%d;\n" % (k * 1024 + j, "-" if v < 0 else "", abs(v))
    h += "        default: lut_rom = 20'sd0;\n    endcase\nendfunction\n"
    h += "function automatic [16:0] exp2_rom(input [7:0] idx);\n    case (idx)\n"
    for j, v in enumerate(G["sm.exp2"]): h += "        8'd%d: exp2_rom = 17'd%d;\n" % (j, int(v))
    h += "        default: exp2_rom = 17'd0;\n    endcase\nendfunction\n"
    return h


ROM_SVH = ROOT / "rtl" / "core" / "imh_rom.svh"


def build_data(tag, outdir, vocab_n=32768):
    G = dict(np.load(golden(f"tiny-{tag}.npz")))
    have = ROM_SVH.read_text()                 # the ROM also holds Poinsetta's asinh table (mkimage_ts.py rom)
    assert all(l in have for l in rom_svh(G).splitlines() if "_rom = " in l),         "golden ROM tables differ from rtl/core/imh_rom.svh (run mkimage_ts.py rom and re-verify)"
    F0 = {k[2:]: int(v) for k, v in G.items() if k.startswith("F:")}
    assert all(0 <= v <= 15 for v in F0.values()), "a format is outside 0..15: the LUT unit takes 4-bit formats"
    meta = json.load(open(golden(f"tiny-{tag}.json")))
    F = {k[2:]: int(v) for k, v in G.items() if k.startswith("F:")}
    blob = bytearray()

    def put(b):
        while len(blob) % 16: blob.append(0xFF)
        off = DATA_BASE + len(blob); blob.extend(b); return off

    sites = []
    for w, fin, fout in mac_sites():
        q = G[w + ".q"]; wb = int(meta["weight_bits"].get(w, 8))
        bi = G[w + ".bi"] if w + ".bi" in G else np.zeros(q.shape[0], dtype=np.int64)
        sites.append((w, put(pack_site(q, G[w + ".M"], G[w + ".sh"], bi, wb)), q.shape[1], q.shape[0], wb, F[fin], F[fout]))
    q = G["emb.q"]; wb = int(meta["weight_bits"].get("emb", 8))
    sites.append(("emb", put(pack_site(q, G["proj.M"], G["proj.sh"], np.zeros(q.shape[0], dtype=np.int64), wb)),
                  q.shape[1], q.shape[0], wb, F["dec.ln"], 10))
    em = np.zeros((q.shape[0], 4), dtype=np.uint8)
    em[:, 0] = G["emb.M"] & 255; em[:, 1] = G["emb.M"] >> 8; em[:, 2] = G["emb.sh"]
    off_embm = put(em.tobytes())
    norms = []
    for n in norm_sites():
        g = G[n + ".G"]; b = G[n + ".B"]
        assert np.abs(g).max() < 32768 and np.abs(b).max() < 2 ** 31
        rec = np.zeros(len(g), dtype=[("g", "<i2"), ("b", "<i4")]); rec["g"] = g; rec["b"] = b
        norms.append((n, put(rec.tobytes()), int(G[n + ".eps"]), int(G[n + ".fg"]), F[n]))
    rope = np.concatenate([G["rope.cos"], G["rope.sin"]], axis=1).astype("<i2")
    off_rope = put(rope.tobytes())
    pieces, _ = vocab_pieces()
    assert len(pieces) == vocab_n
    offs = np.zeros(vocab_n + 1, dtype="<u4"); offs[1:] = np.cumsum([len(p) for p in pieces])
    off_vocab = put(offs.tobytes() + b"".join(pieces))

    h = "// generated by rtl/core/tools/mkimage.py from data/golden/tiny-%s.npz; do not edit\n" % tag
    h += f"#define DATA_BASE {DATA_BASE}u\n#define OFF_EMBM {off_embm}u\n#define OFF_ROPE {off_rope}u\n#define OFF_VOCAB {off_vocab}u\n"
    h += f"#define VOCAB_N {vocab_n}\n#define SM_C {int(G['sm.C'])}\n#define F_ENC_RES {F['enc.res']}\n#define F_DEC_RES {F['dec.res']}\n"
    h += "typedef struct { unsigned off; unsigned short nin, nout; unsigned char wbits; signed char fin, fout; } site_t;\n"
    h += "static const site_t SITES[] = {\n" + "".join(
        f"  {{{o}u, {ni}, {no & 0xFFFF}, {wb}, {fi}, {fo}}}, // {i} {w}\n" for i, (w, o, ni, no, wb, fi, fo) in enumerate(sites)) + "};\n"
    h += "typedef struct { unsigned off; int eps; signed char fg, fout; } norm_t;\n"
    h += "static const norm_t NORMS[] = {\n" + "".join(
        f"  {{{o}u, {e}, {fg}, {fo}}}, // {i} {n}\n" for i, (n, o, e, fg, fo) in enumerate(norms)) + "};\n"
    h += c_array("F_PROD", [F[f"dec{i}.prod"] for i in range(NL)], "signed char")
    for t in ("tanh", "gelu", "silu"): h += c_array("LUT_" + t.upper(), G["lut." + t], "int")
    h += c_array("EXP2", G["sm.exp2"], "unsigned")
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "layout.h").write_text(h, newline="\n")
    (outdir / "data.bin").write_bytes(bytes(blob))
    json.dump(dict(tag=tag, data_base=DATA_BASE, data_bytes=len(blob),
                   sites={w: dict(off=o, nin=ni, nout=no, wbits=wb) for w, o, ni, no, wb, fi, fo in sites},
                   norms={n: o for n, o, e, fg, fo in norms}, off_rope=off_rope, off_embm=off_embm, off_vocab=off_vocab),
              open(outdir / "image.json", "w"), indent=1)
    print(f"data.bin {len(blob)} bytes, {len(sites)} sites -> {outdir}")


def build_flash(outdir, fw):
    fwb = Path(fw).read_bytes()
    assert len(fwb) + 8 <= DATA_BASE, "firmware does not fit below DATA_BASE"
    img = bytearray(b"IMH1" + len(fwb).to_bytes(4, "little") + fwb)
    img.extend(b"\xFF" * (DATA_BASE - len(img)))
    img.extend((outdir / "data.bin").read_bytes())
    (outdir / "flash.bin").write_bytes(bytes(img))
    print(f"flash.bin {len(img)} bytes (firmware {len(fwb)})")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["data", "flash", "rom"])
    ap.add_argument("--tag", default="w8")
    ap.add_argument("--fw", default="")
    ap.add_argument("--out", default="")
    a = ap.parse_args()
    out = Path(a.out) if a.out else ROOT / "data" / "core" / a.tag
    if a.what == "rom":
        ROM_SVH.write_text(rom_svh(dict(np.load(golden(f"tiny-{a.tag}.npz")))), newline="\n"); print("wrote", ROM_SVH)
    elif a.what == "data": build_data(a.tag, out)
    else: build_flash(out, a.fw or out / "fw.bin")
