"""ROM image of the Poinsetta chip from a format-3 golden export (docs/golden-format.md), for rtl/core/fw/stream.c.

    .venv/Scripts/python.exe rtl/core/tools/mkimage_ts.py data [--tag w4c8r] -> data/core/ts-<tag>/{data.bin, layout.h}
    .venv/Scripts/python.exe rtl/core/tools/mkimage_ts.py rom [--tag w4c8r]  -> rtl/core/imh_rom.svh (LUT and exp2 ROMs)

The default tag is the chip's ROM image (paths.ROM_TAG). The LUT ROM belongs to the image: its asinh table carries the
export's frontend scale, so `data` warns when rtl/core/imh_rom.svh holds another export's tables (that build cannot
be bit-exact).

Weight sites are laid out for the fan-out array (rtl/core/imh_fan.sv): per group of 32 output rows, 32 header records
of 8 bytes {bias[39:0], M[15:0], sh[7:0]}, then for each input the 32 rows' weights (int8: 32 bytes; int4: 16 bytes,
low nibble first). The frontend convolutions' columns are reordered from channel-major (c * 5 + tap) to tap-major
(tap * C + c), so that a conv input is 5 consecutive frames of the previous layer, contiguous in RAM.
Row-scaled tables (emb, pos) are rows with a {M u16, sh u8, 0} record per row; a table whose values all fit in 4 bits
(-8..7: the int4 exports) is packed two values per byte, low nibble first (EMB_Q4 / POS_Q4 in layout.h; the firmware
unpacks and sign-extends them), otherwise one int8 per value. Norms: 6-byte records
{G int16, B int32 = 0} per channel. rope: 448 rows of 16 cos + 16 sin (int16). Vocabulary as Imhotep.
"""
import argparse, json, sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import golden, ROOT, ROM_TAG
import mkimage as MI

DATA_BASE = 65536
NL, D, L = 6, 320, 32
ENC = ["q", "k", "v", "o", "fc1", "fc2"]
DEC = ["q", "k", "v", "o", "cq", "ck", "cv", "co", "fc1", "fc2"]


def sites():
    s = ["fe.lin", "fe.c1", "fe.c2"]
    for i in range(NL): s += [f"enc{i}.{k}" for k in ENC]
    for i in range(NL): s += [f"dec{i}.{k}" for k in DEC]
    return s + ["head"]


def norms():
    n = ["fe.cmvn"]
    for i in range(NL): n += [f"enc{i}.ln1", f"enc{i}.ln2"]
    n += ["enc.ln"]
    for i in range(NL): n += [f"dec{i}.ln1", f"dec{i}.ln2", f"dec{i}.ln3"]
    return n + ["dec.ln"]


def tapmajor(q, C):
    """[out, C*5] channel-major (c * 5 + tap) -> tap-major (tap * C + c)."""
    return q.reshape(q.shape[0], C, 5).transpose(0, 2, 1).reshape(q.shape[0], 5 * C)


def pack_fan(q, M, sh, bi, wbits):
    out, nin = q.shape
    assert nin % 16 == 0 and M.min() >= 0 and M.max() < 65536 and sh.min() >= 1 and sh.max() < 62
    assert np.abs(bi).max() < 2 ** 39
    ng = (out + L - 1) // L
    pad = ng * L - out
    q = np.concatenate([q, np.zeros((pad, nin), q.dtype)]); M = np.concatenate([M, np.zeros(pad, np.int64)])
    sh = np.concatenate([sh, np.ones(pad, np.int64)]); bi = np.concatenate([bi, np.zeros(pad, np.int64)])
    hdr = np.zeros((ng * L, 8), np.uint8)
    b = bi.astype(np.int64) & ((1 << 40) - 1)
    for j in range(5): hdr[:, j] = (b >> (8 * j)) & 255
    hdr[:, 5] = M & 255; hdr[:, 6] = M >> 8; hdr[:, 7] = sh
    out_b = bytearray()
    for g in range(ng):
        out_b += hdr[g * L:(g + 1) * L].tobytes()
        w = q[g * L:(g + 1) * L].T                                      # [nin, 32]
        if wbits == 8:
            out_b += w.astype(np.int8).tobytes()
        elif wbits == 16:
            out_b += w.astype("<i2").tobytes()
        else:
            assert wbits == 4 and w.min() >= -8 and w.max() <= 7
            n = w.astype(np.int64) & 15
            out_b += (n[:, 0::2] | (n[:, 1::2] << 4)).astype(np.uint8).tobytes()
    return bytes(out_b)


def rom_svh(G, Gi, tag=""):
    """LUT ROM: table 0 tanh (Imhotep, kept for its firmware), 1 GELU, 2 SiLU, 3 asinh (R = 4); exp2."""
    for t in ("gelu", "silu"):
        assert (np.asarray(G["lut." + t]) == np.asarray(Gi["lut." + t])).all(), t + " table differs from Imhotep's"
    assert (np.asarray(G["sm.exp2"]) == np.asarray(Gi["sm.exp2"])).all()
    h = "// generated by rtl/core/tools/mkimage_ts.py rom%s: lut.tanh (Imhotep), lut.gelu, lut.silu, lut.asinh\n" % (
        " from ts-%s.npz" % tag if tag else "")
    h += "// (Poinsetta), sm.exp2. Do not edit.\n"
    h += "function automatic signed [19:0] lut_rom(input [1:0] sel, input [9:0] idx);\n    case ({sel, idx})\n"
    for k, (src, t) in enumerate(((Gi, "tanh"), (G, "gelu"), (G, "silu"), (G, "asinh"))):
        for j, v in enumerate(src["lut." + t]):
            v = int(v); assert abs(v) < 2 ** 19
            h += "        12'd%d: lut_rom = %s20'sd%d;\n" % (k * 1024 + j, "-" if v < 0 else "", abs(v))
    h += "        default: lut_rom = 20'sd0;\n    endcase\nendfunction\n"
    h += "function automatic [16:0] exp2_rom(input [7:0] idx);\n    case (idx)\n"
    for j, v in enumerate(G["sm.exp2"]): h += "        8'd%d: exp2_rom = 17'd%d;\n" % (j, int(v))
    h += "        default: exp2_rom = 17'd0;\n    endcase\nendfunction\n"
    return h


def build(tag, outdir):
    G = dict(np.load(golden(f"ts-{tag}.npz")))
    assert int(G["version"]) == 3
    have = MI.ROM_SVH.read_text()             # the export's own tables (GELU, SiLU, asinh) in the LUT ROM?
    want = ["        12'd%d: lut_rom = %s20'sd%d;" % (k * 1024 + j, "-" if int(v) < 0 else "", abs(int(v)))
            for k, t in ((1, "gelu"), (2, "silu"), (3, "asinh")) for j, v in enumerate(G["lut." + t])]
    if not all(l in have for l in want):
        print(f"WARNING: rtl/core/imh_rom.svh is not the LUT ROM of ts-{tag}.npz (its asinh table differs): a chip built "
              f"with it is not bit-exact with {tag}; `mkimage_ts.py rom --tag {tag}` makes it so", file=sys.stderr)
    meta = json.load(open(golden(f"ts-{tag}.json")))
    wb = meta["weight_bits"]
    if isinstance(wb, str): wb = eval(wb)
    F = {k[2:]: int(v) for k, v in G.items() if k.startswith("F:")}
    blob = bytearray()

    def put(b):
        while len(blob) % 64: blob.append(0)
        off = DATA_BASE + len(blob); blob.extend(b); return off

    st = []
    for w in sites():
        q = G[w + ".q"]
        if w == "fe.c1": q = tapmajor(q, 320)
        if w == "fe.c2": q = tapmajor(q, 640)
        bi = G[w + ".bi"] if w + ".bi" in G else np.zeros(q.shape[0], np.int64)
        bits = int(wb.get(w, 8))
        bits = 16 if bits > 8 else bits
        assert bits in (4, 8, 16)
        st.append((w, put(pack_fan(q, G[w + ".M"], G[w + ".sh"], bi, bits)), q.shape[1], q.shape[0], bits))
    rows, q4 = {}, {}
    for t in ("emb", "pos"):
        q = G[t + ".q"].astype(np.int8); n = q.shape[0]
        rec = np.zeros((n, 4), np.uint8); rec[:, 0] = G[t + ".M"] & 255; rec[:, 1] = G[t + ".M"] >> 8; rec[:, 2] = G[t + ".sh"]
        q4[t] = bool(q.min() >= -8 and q.max() <= 7 and q.shape[1] % 2 == 0)
        if q4[t]:                        # two values per byte, low nibble first (as the fan-out array's int4 weights)
            u = q.view(np.uint8) & 15
            qb = (u[:, 0::2] | (u[:, 1::2] << 4)).astype(np.uint8)
        else:
            qb = q.view(np.uint8)
        rows[t] = (put(rec.tobytes()), put(qb.tobytes()))
    nm = []
    for n in norms():
        g = G[n + ".G"]
        rec = np.zeros(len(g), dtype=[("g", "<i2"), ("b", "<i4")]); rec["g"] = g
        nm.append((n, put(rec.tobytes()), int(G[n + ".eps"]), int(G[n + ".fg"]), F[n]))
    off_rope = put(np.concatenate([G["rope.cos"], G["rope.sin"]], axis=1).astype("<i2").tobytes())
    pieces, _ = MI.vocab_pieces("UsefulSensors/moonshine-streaming-tiny")
    offs = np.zeros(len(pieces) + 1, dtype="<u4"); offs[1:] = np.cumsum([len(p) for p in pieces])
    off_vocab = put(offs.tobytes() + b"".join(pieces))

    h = f"// generated by rtl/core/tools/mkimage_ts.py from ts-{tag}.npz; do not edit\n"
    h += f"#define DATA_BASE {DATA_BASE}u\n#define OFF_ROPE {off_rope}u\n#define OFF_VOCAB {off_vocab}u\n#define VOCAB_N {len(pieces)}\n"
    h += f"#define OFF_EMB_REC {rows['emb'][0]}u\n#define OFF_EMB_Q {rows['emb'][1]}u\n"
    h += f"#define OFF_POS_REC {rows['pos'][0]}u\n#define OFF_POS_Q {rows['pos'][1]}u\n#define SM_C {int(G['sm.C'])}\n"
    h += f"#define EMB_Q4 {int(q4['emb'])}\n#define POS_Q4 {int(q4['pos'])}\n"
    for k, v in sorted(F.items()):
        h += "#define F_%s %d\n" % (k.replace(".", "_").upper(), v)
    h += "typedef struct { unsigned off; unsigned short nin, nout; unsigned char wbits; } site_t;\n"
    h += "static const site_t SITES[] = {\n" + "".join(
        f"  {{{o}u, {ni}, {no}, {b}}}, // {i} {w}\n" for i, (w, o, ni, no, b) in enumerate(st)) + "};\n"
    h += "typedef struct { unsigned off; int eps; signed char fg, fout; } norm_t;\n"
    h += "static const norm_t NORMS[] = {\n" + "".join(
        f"  {{{o}u, {e}, {fg}, {fo}}}, // {i} {n}\n" for i, (n, o, e, fg, fo) in enumerate(nm)) + "};\n"
    for t in ("gelu", "silu", "asinh"): h += MI.c_array("LUT_" + t.upper(), G["lut." + t], "int")
    h += "#define LUT_TANH LUT_GELU      /* table 0 is Imhotep's tanh; this model does not use it */\n#define LUT_ASINH_N 513\n"
    h += MI.c_array("EXP2", G["sm.exp2"], "unsigned")
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "layout.h").write_text(h, newline="\n")
    (outdir / "data.bin").write_bytes(bytes(blob))
    print(f"data.bin {len(blob)} bytes, {len(st)} sites -> {outdir}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["data", "rom"])
    ap.add_argument("--tag", default=ROM_TAG)
    ap.add_argument("--out", default="")
    a = ap.parse_args()
    if a.what == "rom":
        G = dict(np.load(golden(f"ts-{a.tag}.npz"))); Gi = dict(np.load(golden("tiny-w8.npz")))
        MI.ROM_SVH.write_text(rom_svh(G, Gi, a.tag), newline="\n"); print("wrote", MI.ROM_SVH, "from", a.tag)
    else:
        build(a.tag, Path(a.out) if a.out else ROOT / "data" / "core" / f"ts-{a.tag}")
