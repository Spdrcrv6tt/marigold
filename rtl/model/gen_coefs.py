"""Design the PDM decimator FIR coefficients and write rtl/src/*.mem ($readmemh, signed Q15).

Chain (default): PDM 3.072 MHz -> CIC5 /48 -> 64 kHz -> half-band FIR /2 -> 32 kHz
                 -> compensation FIR /2 -> 16 kHz.
The compensation FIR also undoes the CIC droop, the half-band droop and the CIC gain,
which is not a power of two (R^N against 2^(CIC_W-1)).

Run:  python rtl/model/gen_coefs.py        (needs numpy + scipy; the .mem files are committed)
"""
import os
import numpy as np
from scipy import signal

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")

R, N, CIC_W, CIC_SHIFT = 48, 5, 29, 9
HB_TAPS, FIR_TAPS = 23, 63
FS_PDM = 16000 * 4 * R
PASS_HZ, STOP_HZ = 7000.0, 9000.0


def cic_mag(f, r=R, n=N, fs=FS_PDM):
    """|H| of the CIC normalised to 1 at DC."""
    f = np.atleast_1d(np.asarray(f, dtype=float))
    x = np.pi * f / fs
    s = np.sin(x)
    h = np.ones_like(x)
    nz = np.abs(s) > 1e-12
    h[nz] = np.sin(r * x[nz]) / (r * s[nz])
    return np.abs(h) ** n


def fir_mag(q, f, fs):
    w, h = signal.freqz(np.asarray(q, dtype=float), worN=2 * np.pi * np.atleast_1d(f) / fs)
    return np.abs(h)


def design():
    # Stage A: half-band at 64 kHz. Kaiser-windowed, even taps forced to exactly zero.
    hb = signal.firwin(HB_TAPS, 0.5, window=("kaiser", 8.0))
    c = HB_TAPS // 2
    for i in range(HB_TAPS):
        if i != c and (i - c) % 2 == 0:
            hb[i] = 0.0
    hb[c] = 0.5
    hb_q = np.round(hb * 32768).astype(int)
    hb_q[c] += 32768 - hb_q.sum()        # DC gain exactly 2^15

    # Stage B: least-squares FIR at 32 kHz; passband is the inverse of the droop so far.
    edges = np.linspace(0, PASS_HZ, 29)
    inv = 1.0 / (cic_mag(edges) * fir_mag(hb_q / 32768.0, edges, 64000.0))
    bands, desired = [], []
    for i in range(len(edges) - 1):
        bands += [edges[i], edges[i + 1]]
        desired += [inv[i], inv[i + 1]]
    bands += [STOP_HZ, 16000.0]
    desired += [0.0, 0.0]
    weight = [1.0] * (len(edges) - 1) + [30.0]
    h = signal.firls(FIR_TAPS, bands, desired, weight=weight, fs=32000.0)
    # The CIC output is shifted right by CIC_SHIFT into DW = CIC_W - CIC_SHIFT bits, so the
    # gain left to correct is exactly 2^(CIC_W-1) / R^N.
    gain = float(2 ** (CIC_W - 1)) / float(R ** N)
    fir_q = np.round(h * gain * 32768).astype(int)
    assert np.abs(fir_q).max() < 32768 and np.abs(hb_q).max() < 32768
    return hb_q, fir_q


def write_mem(path, q):
    with open(path, "w", newline="\n") as f:
        for v in q:
            f.write("%04x\n" % (int(v) & 0xFFFF))


def write_svh(path, tables):
    with open(path, "w", newline="\n") as f:
        f.write("// Generated by rtl/model/gen_coefs.py. Do not edit.\n")
        for name, q in tables:
            f.write("function automatic signed [15:0] %s(input [6:0] i);\n  case (i)\n" % name)
            for i, v in enumerate(q):
                v = int(v)
                f.write("    7'd%d: %s = %s16'sd%d;\n" % (i, name, "-" if v < 0 else "", abs(v)))
            f.write("    default: %s = 16'sd0;\n  endcase\nendfunction\n" % name)


if __name__ == "__main__":
    hb_q, fir_q = design()
    write_mem(os.path.join(SRC, "pdm_hb_coef.mem"), hb_q)
    write_mem(os.path.join(SRC, "pdm_fir_coef.mem"), fir_q)
    write_svh(os.path.join(SRC, "pdm_coefs.svh"), [("pdm_hb_coef", hb_q), ("pdm_fir_coef", fir_q)])
    print("hb", list(hb_q))
    print("fir", list(fir_q))
    print("fir dc gain", fir_q.sum() / 32768.0, "target", 2.0 ** (CIC_W - 1) / R ** N)
